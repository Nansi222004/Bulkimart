import express from 'express';
import mongoose from 'mongoose';
import rateLimit from 'express-rate-limit';
import { protect, requireAdmin, requireCustomerSession } from '../middlewares/auth.middleware.js';
import { asyncHandler as wrap } from '../middlewares/error.middleware.js';
import Partner from '../models/DeliveryPartner.js';
import { productionParcel, requireParcel, failParcel, parcelPermission } from '../services/parcelPolicy.service.js';
import * as c from '../controllers/parcelDelivery.controller.js';
const privacy=(_req,res,next)=>{res.set('Cache-Control','private, no-store');next();};
const mutation=(req,_res,next)=>{if(req.method!=='GET' && productionParcel()) failParcel('Production parcel mutations are release-blocked',503);next();};
const body=(req,_res,next)=>{if(req.method==='POST' && (!req.body || Array.isArray(req.body) || typeof req.body!=='object')) failParcel('Object request body required');next();};
const mode=value=>(req,_res,next)=>{req.parcelMode=value;next();};
const permission=key=>(req,_res,next)=>{parcelPermission(req,key);next();};
const feature=key=>(_req,_res,next)=>{requireParcel(key);next();};
const limiter=()=>rateLimit({windowMs:60000,limit:100,standardHeaders:true,legacyHeaders:false});
const errors=(err,_req,_res,next)=>{if(err.name==='VersionError' || err.code===11000){err.status=409;err.message='State changed; refresh and retry using the same request key';}next(err);};
const setup=r=>{r.use(privacy,limiter(),mutation,body);r.param('id',(req,_res,next,id)=>{if(!mongoose.isValidObjectId(id)) failParcel('Invalid booking ID');next();});};
export const customerParcelRouter=express.Router(); setup(customerParcelRouter);
customerParcelRouter.get('/capabilities',c.capabilities);
customerParcelRouter.get('/catalogue',wrap(c.catalogue));
customerParcelRouter.use(protect,requireCustomerSession,(req,_res,next)=>{if(req.tokenRole==='delivery') failParcel('Customer portal session required',403);next();},mode('customer'));
customerParcelRouter.post('/quotes',wrap(c.quote));
customerParcelRouter.post('/bookings',wrap(c.book));
customerParcelRouter.get('/bookings',wrap(c.list));
customerParcelRouter.get('/bookings/:id',wrap(c.detail));
customerParcelRouter.post('/bookings/:id/cancellation',wrap(c.cancel));
customerParcelRouter.post('/bookings/:id/payment',wrap(c.pay));
customerParcelRouter.post('/payments/verify',wrap(c.verify));
customerParcelRouter.post('/bookings/:id/payment-status',wrap(c.paymentStatus));
customerParcelRouter.use(errors);
export const driverParcelRouter=express.Router(); setup(driverParcelRouter);
driverParcelRouter.use(protect,feature('fulfilment'),wrap(async(req,_res,next)=>{
  if(req.userType!=='user' || req.tokenRole && req.tokenRole!=='delivery' || !req.user.roles?.includes('delivery')) failParcel('Delivery session required',403);
  const p=await Partner.findOne({userId:req.user._id,status:'approved'}); if(!p) failParcel('Approved driver required',403);
  req.parcelPartner=p; next();
}),mode('driver'));
driverParcelRouter.get('/bookings',wrap(c.list)); driverParcelRouter.get('/bookings/:id',wrap(c.detail));
driverParcelRouter.post('/bookings/:id/offer',wrap(c.respond)); driverParcelRouter.post('/bookings/:id/actions',wrap(c.driverAction));
driverParcelRouter.use(errors);
export const adminParcelRouter=express.Router(); setup(adminParcelRouter);
adminParcelRouter.use(protect,requireAdmin,permission('manage_orders'),mode('admin'));
adminParcelRouter.get('/bookings',wrap(c.list)); adminParcelRouter.get('/bookings/:id',wrap(c.detail));
adminParcelRouter.get('/bookings/:id/candidates',wrap(c.candidates)); adminParcelRouter.post('/bookings/:id/assign',wrap(c.assign));
adminParcelRouter.post('/bookings/:id/actions',wrap(c.adminAction));
adminParcelRouter.get('/policy',permission('manage_finance'),wrap(c.policies)); adminParcelRouter.post('/policy',permission('manage_finance'),wrap(c.savePolicy));
adminParcelRouter.post('/bookings/:id/refund',permission('manage_finance'),wrap(c.refund));
adminParcelRouter.post('/bookings/:id/recover-payment',permission('manage_finance'),wrap(c.recover));
adminParcelRouter.use(errors);
