import { jest } from '@jest/globals';
import mongoose from 'mongoose';
import express from 'express';
import request from 'supertest';
import jwt from 'jsonwebtoken';
import crypto from 'node:crypto';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
const emitToAdmins = jest.fn();
jest.unstable_mockModule('../socket/rooms.js', () => ({ emitToAdmins, emitToUser: jest.fn(), emitToSeller: jest.fn(), emitToRider: jest.fn() }));
jest.unstable_mockModule('../services/fcm.service.js', () => ({ sendPushNotification: jest.fn(), sendBulkNotification: jest.fn() }));
const { customerLegalRouter } = await import('../routes/legalServices.routes.js');
const { getAdminNotifications, getAdminUnreadCount } = await import('../controllers/admin.controller.js');
const { protect, requireAdmin } = await import('../middlewares/auth.middleware.js');
const { errorHandler } = await import('../middlewares/error.middleware.js');
const { JWT_SECRET } = await import('../config/jwt.js');
const { default: Application } = await import('../models/ServiceApplication.js');
const { default: Service } = await import('../models/Service.js');
const { default: User } = await import('../models/User.js');
const { default: Admin } = await import('../models/Admin.js');
const { default: Notification } = await import('../models/Notification.js');
let db, user, admins, service;
const app = express(); app.use(express.json()); app.use('/api/customer-services', customerLegalRouter);
app.get('/inbox', protect, requireAdmin, getAdminNotifications); app.get('/count', protect, requireAdmin, getAdminUnreadCount); app.use(errorHandler);
const auth = (req, account, type, role) => req.set('Authorization', `Bearer ${jwt.sign({ id: String(account._id), type, ...(role ? { role } : {}) }, JWT_SECRET)}`);
beforeAll(async () => {
  db = await MongoMemoryReplSet.create({ binary: { version: '7.0.14' }, replSet: { count: 1 } }); await mongoose.connect(db.getUri());
  await Promise.all([Application.init(), Notification.init()]);
});
afterAll(async () => { await mongoose.disconnect(); await db.stop(); });
beforeEach(async () => {
  for (const collection of Object.values(mongoose.connection.collections)) await collection.deleteMany({});
  jest.clearAllMocks();
  user = await User.create({ phone: '9876500123', roles: ['buyer'], isActive: true });
  admins = [0, 1, 2].map(index => ({ _id: new mongoose.Types.ObjectId(), email: `admin-${index}@example.test`, role: 'superAdmin', isActive: index !== 2 }));
  await Admin.collection.insertMany(admins);
  service = await Service.create({ name: 'Legal notification fixture', slug: 'legal-notification-fixture', audiences: ['customer'], status: 'published', pricing: { mode: 'free', amount: 0, currency: 'INR' }, fields: [] });
});
test('a customer request persists an unread notification per active admin, emits a live signal, and appears in the authenticated inbox', async () => {
  const submit = key => auth(request(app).post(`/api/customer-services/catalogue/${service._id}/applications`), user, 'user', 'buyer').set('Idempotency-Key', key).field('answers', '{}').field('formVersion', service.formVersion).field('serviceVersion', service.__v);
  const key = crypto.randomUUID(), created = (await submit(key).expect(201)).body.data;
  await new Promise(resolve => setImmediate(resolve));
  const rows = await Notification.find({ recipientModel: 'Admin', 'metadata.applicationId': created._id }).lean();
  expect(rows).toHaveLength(2); expect(rows.every(row => !row.isRead && row.route === `/admin/services?legalRequest=${created._id}`)).toBe(true);
  expect(emitToAdmins).toHaveBeenCalledWith('notification_new', expect.objectContaining({ metadata: expect.objectContaining({ applicationId: String(created._id) }) }));
  const inbox = await auth(request(app).get('/inbox'), admins[0], 'admin').expect(200);
  expect(inbox.body.data.map(row => row._id)).toEqual([String(rows.find(row => String(row.userId) === String(admins[0]._id))._id)]);
  expect((await auth(request(app).get('/count'), admins[0], 'admin').expect(200)).body.data.count).toBe(1);
  await submit(key).expect(200);
  expect(await Notification.countDocuments({ recipientModel: 'Admin', 'metadata.applicationId': created._id })).toBe(2);
});
